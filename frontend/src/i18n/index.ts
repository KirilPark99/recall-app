const dicts: Record<Locale, Partial<Dict>> = { ru, en };

export function translate(locale: Locale, key: keyof Dict, params?: Record<string, string | number>): string {
  const dict = dicts[locale] ?? ru;
  let text = (dict[key] as string | undefined) ?? (ru[key] as string);
  if (text === undefined) {
    devLog(`missing i18n key: ${key}`);
    text = key;
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

// Русская плюрализация: 1 карточка, 2 карточки, 5 карточек; en: 1 card, 2 cards.
export function plural(locale: Locale, count: number, forms: [string, string, string]): string {
  if (locale === "ru") {
    const n = Math.abs(count) % 100;
    const n1 = n % 10;
    if (n > 10 && n < 20) return forms[2];
    if (n1 > 1 && n1 < 5) return forms[1];
    if (n1 === 1) return forms[0];
    return forms[2];
  }
  return count === 1 ? forms[0] : forms[2];
}

export function cardsLabel(locale: Locale, count: number): string {
  return `${count} ${plural(locale, count, ["карточка", "карточки", "карточек"])}`;
}

export function formatDate(value: string | Date | null | undefined, locale: Locale): string {
  if (!value) return "";
  const d = typeof value === "string" ? new Date(value) : value;
  return d.toLocaleDateString(locale === "ru" ? "ru-RU" : "en-US", { day: "numeric", month: "short", year: "numeric" });
}

export function formatRelative(value: string | Date | null | undefined, locale: Locale): string {
  if (!value) return "";
  const d = typeof value === "string" ? new Date(value) : value;
  const diffMs = Date.now() - d.getTime();
  const rtf = new Intl.RelativeTimeFormat(locale === "ru" ? "ru" : "en", { numeric: "auto" });
  const minutes = Math.round(diffMs / 60000);
  if (Math.abs(minutes) < 60) return rtf.format(-minutes, "minute");
  const hours = Math.round(minutes / 60);
  if (Math.abs(hours) < 24) return rtf.format(-hours, "hour");
  return rtf.format(-Math.round(hours / 24), "day");
}
